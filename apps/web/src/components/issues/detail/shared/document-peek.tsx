"use client";

import { HugeiconsIcon } from "@hugeicons/react";
import { ArrowLeft01Icon } from "@hugeicons/core-free-icons";

import { SkeletonReveal } from "@/components/ui/skeleton-reveal";
import { DocBlockView, docBlockKey } from "@/components/docs/document-blocks";
import { resolveDocumentSourceMeta } from "@/constants/document-source-meta";
import { useDocument } from "@/hooks/docs/use-documents";
import { splitDocBlocks } from "@/lib/docs/markdown";
import { canEditDocument } from "@/lib/issues/story-documents";
import { cn } from "@/lib/utils";
import { EDocumentSource } from "@/types";

/** Compact read-only document viewer for the peek sheet (`?doc=` param). */
export function IssueDocumentPeek({
  workspaceSlug,
  documentId,
  onBack,
}: {
  workspaceSlug: string;
  documentId: string;
  onBack: () => void;
}) {
  const { data: doc, isPending, isError } = useDocument(workspaceSlug, documentId);

  return (
    <div className="flex h-full min-h-0 flex-col">
      <header className="flex shrink-0 items-center gap-3 border-b px-4 py-3">
        <button
          type="button"
          onClick={onBack}
          className="inline-flex items-center gap-1 text-sm text-muted-foreground transition-colors duration-150 ease-out hover:text-foreground active:scale-[0.97]"
        >
          <HugeiconsIcon icon={ArrowLeft01Icon} className="size-4" />
          Back
        </button>
        {doc ? (
          <span className="min-w-0 truncate text-sm font-medium">{doc.title}</span>
        ) : null}
      </header>

      <div className="min-h-0 flex-1 overflow-y-auto px-5 py-4">
        <SkeletonReveal
          isLoading={isPending}
          skeleton={<div className="h-64 rounded-lg bg-muted" />}
        >
          {isError || !doc ? (
            <p className="text-sm text-muted-foreground">Couldn&apos;t load this document.</p>
          ) : (
            <>
              <div className="mb-4 flex flex-wrap items-center gap-2">
                <span
                  className={cn(
                    "inline-flex rounded-full border px-2 py-0.5 text-[10px] font-medium",
                    resolveDocumentSourceMeta(doc.source).badgeClass,
                  )}
                >
                  {resolveDocumentSourceMeta(doc.source).label}
                </span>
                {doc.source === EDocumentSource.Agent ? (
                  <span className="text-xs text-muted-foreground">Read-only · generated by AI</span>
                ) : null}
                {!canEditDocument(doc) ? null : (
                  <span className="text-xs text-muted-foreground">Uploaded by you</span>
                )}
              </div>
              <article className="prose prose-sm dark:prose-invert max-w-none gn-prose">
                {splitDocBlocks(doc.content).map((block, i) => (
                  <DocBlockView key={docBlockKey(block, i)} block={block} />
                ))}
              </article>
            </>
          )}
        </SkeletonReveal>
      </div>
    </div>
  );
}
