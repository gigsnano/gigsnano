/** Fallback label for unknown segments: "my-cool-thing" → "My Cool Thing". */
export function titleCaseSegment(segment: string): string {
  return segment
    .split("-")
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1) : w))
    .join(" ");
}
