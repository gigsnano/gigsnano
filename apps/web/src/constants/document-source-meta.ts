import { EDocumentSource } from "@/types";

export interface IDocumentSourceMeta {
  label: string;
  hint: string;
  badgeClass: string;
}

export const DOCUMENT_SOURCE_META: Record<EDocumentSource, IDocumentSourceMeta> = {
  [EDocumentSource.Agent]: {
    label: "AI",
    hint: "Generated by the agent — read-only",
    badgeClass: "border-primary/30 bg-primary/10 text-primary",
  },
  [EDocumentSource.User]: {
    label: "Upload",
    hint: "Uploaded by a teammate — you can remove this",
    badgeClass: "border-border bg-muted text-muted-foreground",
  },
};

/**
 * Resolve badge metadata for a document's `source`, tolerating values the
 * backend may omit or add later. The API response is external data — treating
 * `source` as an always-valid enum key crashes the whole detail view when a
 * document arrives without one. Unknown/missing sources fall back to the
 * neutral "Upload" styling.
 */
export function resolveDocumentSourceMeta(
  source: EDocumentSource | string | null | undefined,
): IDocumentSourceMeta {
  return (
    DOCUMENT_SOURCE_META[source as EDocumentSource] ??
    DOCUMENT_SOURCE_META[EDocumentSource.User]
  );
}
