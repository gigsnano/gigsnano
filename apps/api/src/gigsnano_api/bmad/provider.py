"""The LLMProvider seam (spec §5.5). Messages API in production; FakeProvider in
tests and keyless dev. The Claude Agent SDK slots in behind the same interface
when Phase-4 dev-story work arrives."""

from collections.abc import AsyncIterator
from dataclasses import dataclass
from typing import Protocol
from uuid import uuid4

from anthropic import AsyncAnthropic
from fastapi import Request

PROPOSE_FINALIZE_TOOL = {
    "name": "propose_finalize",
    "description": (
        "Call this when the workflow has converged and the artifact is ready to be "
        "generated. The user will then explicitly trigger document generation."
    ),
    "input_schema": {"type": "object", "properties": {}},
}


@dataclass
class TurnDelta:
    text: str


@dataclass
class TurnFinal:
    proposed_finalize: bool
    input_tokens: int | None = None
    output_tokens: int | None = None



@dataclass
class ExtractResult:
    data: dict
    input_tokens: int | None = None
    output_tokens: int | None = None


@dataclass
class RoundDelta:
    text: str


@dataclass
class ToolUse:
    id: str
    name: str
    input: dict


@dataclass
class RoundResult:
    assistant_content: list[dict]
    stop_reason: str
    tool_uses: list[ToolUse]
    input_tokens: int | None = None
    output_tokens: int | None = None


class LLMProvider(Protocol):
    def stream_turn(
        self, *, system: list[dict], messages: list[dict], model: str | None = None
    ) -> AsyncIterator[TurnDelta | TurnFinal]: ...

    async def extract(
        self, *, system: list[dict], messages: list[dict], tool_name: str, schema: dict
    ) -> ExtractResult: ...

    def stream_round(
        self,
        *,
        system: list[dict],
        messages: list[dict],
        tools: list[dict],
        model: str | None = None,
    ) -> AsyncIterator[RoundDelta | RoundResult]: ...


_CANNED = (
    "Thanks — I have what I need to keep going. Tell me more about what you have "
    "in mind, and I'll structure it as we talk. (FakeProvider: set "
    "ANTHROPIC_API_KEY to chat with the real model.)"
)


_PLACEHOLDER = (
    "_Generated by the keyless FakeProvider. Set ANTHROPIC_API_KEY to have a real "
    "model author this document from the conversation._"
)


def _synthesize(node: dict, root: dict, key: str = "") -> object:
    """Build a minimal instance that satisfies a pydantic-emitted JSON schema.

    Only required fields are populated (fields with defaults are left out and
    pydantic fills them). Used by FakeProvider in keyless dev so finalize yields a
    valid canned artifact rather than failing extraction."""
    if "$ref" in node:
        ref = node["$ref"].split("/")[-1]
        return _synthesize(root.get("$defs", {}).get(ref, {}), root, key)
    for combinator in ("anyOf", "oneOf", "allOf"):
        if combinator in node:
            # Prefer a non-null branch (e.g. Optional[...] → the real type).
            branches = [b for b in node[combinator] if b.get("type") != "null"]
            return _synthesize((branches or node[combinator])[0], root, key)
    if "const" in node:
        return node["const"]
    if node.get("enum"):
        return node["enum"][0]
    node_type = node.get("type")
    if node_type == "object":
        required = set(node.get("required", []))
        props = node.get("properties", {})
        return {
            name: _synthesize(sub, root, name)
            for name, sub in props.items()
            if name in required
        }
    if node_type == "array":
        count = max(1, int(node.get("minItems", 0)))
        item_schema = node.get("items", {})
        return [_synthesize(item_schema, root, key) for _ in range(count)]
    if node_type == "integer":
        return int(node.get("minimum", 0))
    if node_type == "number":
        return float(node.get("minimum", 0))
    if node_type == "boolean":
        return False
    # string (default): give readable content for the two well-known keys.
    if key == "title":
        return "Draft Artifact (FakeProvider)"
    if key == "markdown":
        return f"# Draft Artifact\n\n{_PLACEHOLDER}"
    if key == "name":
        return "Sprint 1"
    return _PLACEHOLDER


class FakeProvider:
    """Deterministic provider for tests and keyless local dev."""

    def __init__(
        self,
        turns: list[tuple[str, bool]] | None = None,
        extractions: list[dict | Exception] | None = None,
        rounds: list[dict] | None = None,
    ) -> None:
        self._turns = list(turns) if turns is not None else None
        self._extractions = list(extractions) if extractions is not None else None
        self._rounds = list(rounds) if rounds is not None else None

    async def stream_turn(
        self, *, system: list[dict], messages: list[dict], model: str | None = None
    ) -> AsyncIterator[TurnDelta | TurnFinal]:
        if self._turns is not None:
            if not self._turns:
                raise AssertionError("FakeProvider ran out of scripted turns")
            text, propose = self._turns.pop(0)
        else:
            text, propose = _CANNED, False
        # Two chunks so SSE consumers exercise multi-delta handling.
        mid = max(1, len(text) // 2)
        yield TurnDelta(text[:mid])
        yield TurnDelta(text[mid:])
        yield TurnFinal(proposed_finalize=propose, input_tokens=10, output_tokens=20)

    async def extract(
        self, *, system: list[dict], messages: list[dict], tool_name: str, schema: dict
    ) -> ExtractResult:
        if self._extractions is None:
            # Keyless dev: no script → synthesize a schema-valid placeholder so the
            # finalize path produces a real (canned) artifact instead of 502ing.
            return ExtractResult(
                data=_synthesize(schema, schema),
                input_tokens=10,
                output_tokens=20,
            )
        if not self._extractions:
            raise AssertionError("FakeProvider.extract ran out of scripted extractions")
        item = self._extractions.pop(0)
        if isinstance(item, Exception):
            raise item
        data = item.data if isinstance(item, ExtractResult) else item
        return ExtractResult(data=data, input_tokens=10, output_tokens=20)

    async def stream_round(
        self,
        *,
        system: list[dict],
        messages: list[dict],
        tools: list[dict],
        model: str | None = None,
    ) -> AsyncIterator[RoundDelta | RoundResult]:
        if self._rounds is not None:
            if not self._rounds:
                raise AssertionError("FakeProvider ran out of scripted rounds")
            round_ = self._rounds.pop(0)
        elif self._turns is not None:
            # BMAD tests script `turns=[(text, proposed)]`; translate the next turn
            # into one round so the unified run_agent path exercises them unchanged.
            if not self._turns:
                raise AssertionError("FakeProvider ran out of scripted turns")
            text, propose = self._turns.pop(0)
            yield RoundDelta(text)
            content: list[dict] = [{"type": "text", "text": text}]
            tool_uses: list[ToolUse] = []
            if propose:
                tid = str(uuid4())
                content.append(
                    {"type": "tool_use", "id": tid, "name": "propose_finalize", "input": {}}
                )
                tool_uses = [ToolUse(id=tid, name="propose_finalize", input={})]
            yield RoundResult(
                assistant_content=content,
                stop_reason="tool_use" if propose else "end_turn",
                tool_uses=tool_uses,
                input_tokens=10,
                output_tokens=20,
            )
            return
        else:
            round_ = {"text": _CANNED}
        if "tool" in round_:
            tool_use = ToolUse(
                id=round_["id"], name=round_["tool"], input=round_["input"]
            )
            yield RoundResult(
                assistant_content=[
                    {
                        "type": "tool_use",
                        "id": tool_use.id,
                        "name": tool_use.name,
                        "input": tool_use.input,
                    }
                ],
                stop_reason="tool_use",
                tool_uses=[tool_use],
                input_tokens=10,
                output_tokens=20,
            )
        else:
            text = round_["text"]
            yield RoundDelta(text)
            yield RoundResult(
                assistant_content=[{"type": "text", "text": text}],
                stop_reason="end_turn",
                tool_uses=[],
                input_tokens=10,
                output_tokens=20,
            )


class AnthropicProvider:
    def __init__(self, api_key: str, model: str, max_tokens: int = 4096) -> None:
        self.model = model
        self.max_tokens = max_tokens
        self._client = AsyncAnthropic(api_key=api_key)

    async def stream_turn(
        self, *, system: list[dict], messages: list[dict], model: str | None = None
    ) -> AsyncIterator[TurnDelta | TurnFinal]:
        async with self._client.messages.stream(
            model=model or self.model,
            max_tokens=self.max_tokens,
            system=system,
            messages=messages,
            tools=[PROPOSE_FINALIZE_TOOL],
        ) as stream:
            async for text in stream.text_stream:
                yield TurnDelta(text)
            final = await stream.get_final_message()
        proposed = any(
            block.type == "tool_use" and block.name == "propose_finalize"
            for block in final.content
        )
        yield TurnFinal(
            proposed_finalize=proposed,
            input_tokens=final.usage.input_tokens,
            output_tokens=final.usage.output_tokens,
        )

    async def extract(
        self, *, system: list[dict], messages: list[dict], tool_name: str, schema: dict
    ) -> ExtractResult:
        response = await self._client.messages.create(
            model=self.model,
            max_tokens=self.max_tokens,
            system=system,
            messages=messages,
            tools=[{"name": tool_name, "input_schema": schema}],
            tool_choice={"type": "tool", "name": tool_name},
        )
        # A forced tool call that hits the token ceiling returns a truncated
        # (partial-JSON) tool_use whose input fails schema validation — and a
        # blind retry just truncates again. Fail loudly and diagnosably instead
        # of looping. (This is what silently broke large-artifact finalize when
        # the cap was 4096; keep the signal even after raising the ceiling.)
        if response.stop_reason == "max_tokens":
            raise ValueError(
                f"Artifact extraction truncated at max_tokens={self.max_tokens}; "
                "the document is larger than the output budget."
            )
        usage = response.usage
        input_tokens = usage.input_tokens if usage else None
        output_tokens = usage.output_tokens if usage else None
        for block in response.content:
            if block.type == "tool_use" and block.name == tool_name:
                return ExtractResult(
                    data=dict(block.input),
                    input_tokens=input_tokens,
                    output_tokens=output_tokens,
                )
        raise ValueError("Model returned no tool_use block")

    async def stream_round(
        self,
        *,
        system: list[dict],
        messages: list[dict],
        tools: list[dict],
        model: str | None = None,
    ) -> AsyncIterator[RoundDelta | RoundResult]:
        async with self._client.messages.stream(
            model=model or self.model,
            max_tokens=self.max_tokens,
            system=system,
            messages=messages,
            tools=tools,
        ) as stream:
            async for text in stream.text_stream:
                yield RoundDelta(text)
            final = await stream.get_final_message()
        # exclude_none: the Anthropic SDK's TextBlock now carries a `parsed_output`
        # field (default None) that the API rejects as an extra input when the block is
        # replayed as assistant content in the next tool-loop round.
        assistant_content = [block.model_dump(exclude_none=True) for block in final.content]
        tool_uses = [
            ToolUse(id=block.id, name=block.name, input=dict(block.input))
            for block in final.content
            if block.type == "tool_use"
        ]
        yield RoundResult(
            assistant_content=assistant_content,
            stop_reason=final.stop_reason,
            tool_uses=tool_uses,
            input_tokens=final.usage.input_tokens,
            output_tokens=final.usage.output_tokens,
        )


def build_default_provider() -> LLMProvider:
    from gigsnano_api.core.config import settings

    if settings.anthropic_api_key:
        return AnthropicProvider(
            api_key=settings.anthropic_api_key,
            model=settings.anthropic_model,
            max_tokens=settings.llm_max_tokens,
        )
    return FakeProvider()


def get_llm_provider(request: Request) -> LLMProvider:
    return request.app.state.llm_provider
