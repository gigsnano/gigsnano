from gigsnano_api.bmad.markdown_html import markdown_or_html_to_html, markdown_to_html


def test_markdown_or_html_passes_html_through_and_converts_markdown():
    # Already-HTML input is returned unchanged (not escaped) — GIN-117.
    html = "<p>Add <code>deleted_at</code></p><ul><li>x</li></ul>"
    assert markdown_or_html_to_html(html) == html
    # Plain Markdown is still converted.
    assert markdown_or_html_to_html("- a\n- b") == "<ul><li>a</li><li>b</li></ul>"
    # Prose with a bare "<" is treated as Markdown (escaped), not mistaken for HTML.
    assert markdown_or_html_to_html("a < b and c > d") == "<p>a &lt; b and c &gt; d</p>"


def test_headings_lists_and_paragraphs():
    md = "## Summary\n\nA short intro line.\n\n- first item\n- second item"
    html = markdown_to_html(md)
    assert html == (
        "<h2>Summary</h2>"
        "<p>A short intro line.</p>"
        "<ul><li>first item</li><li>second item</li></ul>"
    )


def test_ordered_list():
    html = markdown_to_html("1. one\n2. two")
    assert html == "<ol><li>one</li><li>two</li></ol>"


def test_inline_bold_italic_code():
    html = markdown_to_html("Use **bold**, _italic_, and `code`.")
    assert html == "<p>Use <strong>bold</strong>, <em>italic</em>, and <code>code</code>.</p>"


def test_escapes_html_so_model_output_cannot_inject_markup():
    html = markdown_to_html("A <script>alert(1)</script> & B")
    assert "<script>" not in html
    assert "&lt;script&gt;" in html
    assert "&amp;" in html


def test_fakeprovider_placeholder_is_valid_html():
    # Mirrors FakeProvider._synthesize output for a `markdown` field in keyless dev.
    md = "# Draft Artifact\n\n_Generated by the keyless FakeProvider._"
    html = markdown_to_html(md)
    assert html == (
        "<h1>Draft Artifact</h1><p><em>Generated by the keyless FakeProvider.</em></p>"
    )


def test_empty_input_returns_empty_paragraph():
    assert markdown_to_html("") == "<p></p>"
    assert markdown_to_html("   \n  \n") == "<p></p>"


def test_code_span_protects_intraword_underscores():
    # snake_case identifiers in `code` must not be italicised (find_api_flow bug).
    html = markdown_to_html("**bold** in `find_api_flow` and `trace_path`")
    assert html == "<p><strong>bold</strong> in <code>find_api_flow</code> and <code>trace_path</code></p>"
    # italics outside code still work
    assert markdown_to_html("a *word* here") == "<p>a <em>word</em> here</p>"
